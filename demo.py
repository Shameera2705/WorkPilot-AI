"""Deterministic offline demo for setup/testing when no API key is available.
This is NOT the LLM-driven agent; it exercises tools and independent verification.
"""
from tools import inspect_tickets, search_knowledge_base, write_report, verify_report
from storage import start_run, log_event, finish_run

def run_offline_demo():
    task = "Offline demo: triage support tickets and create a verified action plan."
    run_id = start_run(task)
    try:
        dataset = inspect_tickets()
        log_event(run_id, "tool_succeeded", {"name": "inspect_tickets", "ticket_count": dataset["ticket_count"]})
        policy = search_knowledge_base("urgent SLA escalation refund outage")
        log_event(run_id, "tool_succeeded", {"name": "search_knowledge_base", "matches": len(policy["matches"])})
        urgent = [t for t in dataset["tickets"] if t["urgent"]]
        lines = [
            "# WorkPilot AI — Support Action Plan", "",
            "> Generated by the deterministic offline demo. This report was not produced by an LLM.", "",
            "## Summary", "",
            f"- Tickets reviewed: {dataset['ticket_count']}",
            f"- Urgent tickets: {len(urgent)}", "",
            "## Priority actions", ""
        ]
        for ticket in urgent:
            lines.extend([
                f"### {ticket['ticket_id']} — {ticket['priority']} priority",
                f"- Customer: {ticket['customer']}",
                f"- Issue: {ticket['issue']}",
                f"- Open for: {ticket['hours_open']} hours",
                "- Recommended action: Assign an owner immediately, acknowledge the customer, investigate the issue, and document the next update.",
                ""
            ])
        lines.extend(["## Knowledge-base findings", ""])
        if policy["matches"]:
            for match in policy["matches"][:8]:
                lines.append(f"- `{match['file']}:{match['line']}` — {match['text']}")
        else:
            lines.append("- No matching policy lines found; do not infer a policy from this absence.")
        lines.extend(["", "## Verification", "",
                      "The report should include all ticket IDs classified as urgent by the deterministic rule.",
                      ""])
        write_result = write_report("\n".join(lines))
        log_event(run_id, "tool_succeeded", {"name": "write_report", "result": write_result})
        verification = verify_report()
        log_event(run_id, "verification", verification)
        status = "verified_success" if verification["passed"] else "not_verified"
        result = {"run_id": run_id, "status": status, "mode": "offline_demo",
                  "tickets_reviewed": dataset["ticket_count"], "urgent_tickets": [t["ticket_id"] for t in urgent],
                  "knowledge_matches": len(policy["matches"]), "report_path": write_result["path"],
                  "verification": verification}
        finish_run(run_id, status, result)
        return result
    except Exception as exc:
        result = {"run_id": run_id, "status": "failed", "mode": "offline_demo",
                  "error": f"{type(exc).__name__}: {exc}"}
        finish_run(run_id, "failed", result)
        return result
